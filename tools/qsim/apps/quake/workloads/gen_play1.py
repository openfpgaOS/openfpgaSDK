def measure(lines, tag):
    cfg = os.path.join(WORK, f"{tag}.cfg")
    out = os.path.join(WORK, tag)
    open(cfg, "w").write("\n".join(lines + ["edict 1", "wait", "echo QSIM_END"]) + "\n")
    subprocess.run([QSIM, ELF, "--app", APP_PROFILE, "--data-dir", PAK_DIR, "--out", out, "--quiet",
                    "--file", f"play1.cfg={cfg}",
                    "--args", "+exec play1.cfg +host_framerate 0.1", "--end-on", "QSIM_END"],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    con = open(os.path.join(out, "console.log"), errors="replace").read()
    blk = con[con.rindex("EDICT 1:"):]
    org = [float(x) for x in re.search(r"^origin\s+'([^']*)'", blk, re.M).group(1).split()]
    va = [float(x) for x in re.search(r"^v_angle\s+'([^']*)'", blk, re.M).group(1).split()]
    mm = re.search(r"^movetype\s+(\S+)", blk, re.M)       # ED_Print omits zero fields: none = MOVETYPE_NONE
    mt = float(mm.group(1)) if mm else 0.0
    return org, va, mt


def main():
    global QSIM, APP_PROFILE, ELF, PAK_DIR, WORK
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("elf")
    ap.add_argument("--pak-dir", default=os.environ.get("QSIM_DATA_DIR", os.environ.get("QSIM_PAK_DIR", "")),
                    help="Quake id1 directory (default $QSIM_DATA_DIR)")
    ap.add_argument("--work", default=os.path.join(HERE, "gen_play1.work"))
    ap.add_argument("--out", default=os.path.join(HERE, "play1.cfg"))
    a = ap.parse_args()
    QSIM = os.path.join(HERE, "..", "..", "..", "qsim")           # tools/qsim/qsim
    APP_PROFILE = os.path.join(HERE, "..", "quake.app")
    ELF, PAK_DIR, WORK = os.path.abspath(a.elf), a.pak_dir, a.work
    os.makedirs(WORK, exist_ok=True)

    ents = load(MAP)
    models = bsp_models(MAP)
    trig = [e for e in ents if e.get("classname") == "trigger_changelevel"][0]
    m = models[int(trig["model"][1:])]
    target = [(m[i] + m[i + 3]) / 2 for i in range(3)]
    print(f"exit trigger {trig.get('map')}: mins {m[0:3]} maxs {m[3:6]} center {target}")

    lines = head_lines() + FIGHT
    n = 0
    for leg in range(6):
        org, va, mt = measure(lines, f"m{n}")
        n += 1
        if mt == 0:
            print(f"leg {leg}: intermission started (movetype 0, origin {org})")
            break
        dx, dy = target[0] - org[0], target[1] - org[1]
        dist = math.hypot(dx, dy)
        print(f"leg {leg}: origin {org} v_angle {va} -> {dist:.1f} units to the trigger center")
        if dist < 12 and abs(target[2] - org[2]) < 40:
            break
        want = math.degrees(math.atan2(dy, dx)) % 360
        # turn until the server yaw (one byte) is within one step of the bearing
        for it in range(4):
            err = (want - va[1] + 540) % 360 - 180
            if abs(err) <= 1.41:
                break
            lines += [f"cl_yawspeed {abs(err) * 20:.1f}", "tl" if err > 0 else "tr", "wait"]
            org, va, mt = measure(lines, f"m{n}")
            n += 1
            print(f"   turned {err:+.2f}: v_angle yaw {va[1]}")
        # a far leg stops short of the trigger and re-measures; the last one goes to the center
        go = dist if dist < 400 else dist - 250
        k = max(1, math.ceil(go / 32 + 0.5))
        v = min(320, max(20, int(round(go / (0.1 * (k - 0.5))))))
        lines += [f"cl_forwardspeed {v}", "+forward"] + ([W(k - 1)] if k > 1 else []) + ["-forward", "wait",
                                                                                          "cl_forwardspeed 400"]
        dz = target[2] - org[2]
        if abs(dz) > 30 and dist < 400:
            kz = max(1, math.ceil(abs(dz) / 20 + 0.5))
            vz = min(320, max(10, int(round(abs(dz) / (0.1 * (kz - 0.5))))))
            key = "moveup" if dz > 0 else "movedown"
            lines += [f"cl_upspeed {vz}", f"+{key}"] + ([W(kz - 1)] if kz > 1 else []) + [f"-{key}", "wait",
                                                                                          "cl_upspeed 200"]
    lines += TAIL
    text = "\n".join(lines) + "\n"
    open(a.out, "w").write(text)
    print(f"wrote {a.out} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
