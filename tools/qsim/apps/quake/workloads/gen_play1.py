"""gen_play1.py <baseline.elf> [--pak-dir DIR] -- regenerate apps/quake/workloads/play1.cfg.

play1.cfg is checked in; this script documents (and can reproduce) how its navigation
numbers were derived.  The script is plain Quake console commands with "wait" timing, so
it is open-loop: the two noclip flights use numbers measured on the BASELINE ELF.

  1. Start of e3m1 -> the deathmatch spot next to a group of grunts/enforcers/dogs:
     computed from the BSP entity lump (start origin/angle, spot origin).
  2. Fight, user-interface phase (fixed text below).
  3. Wherever the fight left the player -> the level exit (trigger_changelevel brush):
     measured.  The generator appends "edict 1" (prints origin and v_angle), runs qsim,
     reads the position, appends one flight leg and repeats; the last leg ends inside the
     trigger, which starts the intermission.

Noclip movement (sv_user.c SV_AirMove): velocity = wish velocity, no z from forward,
clamped to sv_maxspeed 320.  Keys: the frame a key goes down counts 0.5 (CL_KeyState),
held frames 1.0, the release frame 0.  Yaw reaches the server as one byte
(MSG_WriteAngle: (int)deg * 256 / 360), so every leg re-measures v_angle and corrects.
"""
import argparse
import math
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from mapents import load, vec  # noqa: E402

import struct  # noqa: E402

MAP = "e3m1"
FIGHT_SPOT = [616.0, -1128.0, -56.0]     # info_player_deathmatch next to army/enforcer/dog spawns


def bsp_models(mapname):
    for p in ["PAK0.PAK", "PAK1.PAK"]:
        f = open(os.path.join(PAK_DIR, p), "rb")
        magic, off, ln = struct.unpack("<4sii", f.read(12))
        f.seek(off)
        d = f.read(ln)
        for i in range(ln // 64):
            name, fo, fl = struct.unpack("<56sii", d[i * 64:(i + 1) * 64])
            if name.split(b"\0")[0].decode() == f"maps/{mapname}.bsp":
                f.seek(fo)
                b = f.read(fl)
                mo, ml = struct.unpack("<ii", b[4 + 14 * 8:4 + 14 * 8 + 8])
                return [struct.unpack("<9f7i", b[mo + i * 64:mo + (i + 1) * 64]) for i in range(ml // 64)]


def W(k):
    return ";".join(["wait"] * k) if k > 0 else ""


def head_lines():
    ents = load(MAP)
    st = [e for e in ents if e.get("classname") == "info_player_start"][0]
    so = vec(st["origin"])
    ang = float(st.get("angle", "0"))
    dx, dy, dz = FIGHT_SPOT[0] - so[0], FIGHT_SPOT[1] - so[1], FIGHT_SPOT[2] - so[2]
    b = (math.degrees(math.atan2(dy, dx)) - ang + 540) % 360 - 180
    dist = math.hypot(dx, dy)
    kz = round((abs(dz) - 10) / 20) + 1
    kf = round((dist - 20) / 32) + 1
    return f"""// qsim workload play1: a live single-player game (README "The gate: what it catches").  Generated by gen_play1.py.
// qsim ... --app apps/quake/quake.app --file play1.cfg=apps/quake/workloads/play1.cfg
//          --args "+exec play1.cfg +host_framerate 0.1"
//          --window-on QSIM_WINDOW --window-end-on QSIM_WINDOW_END --end-on QSIM_END
// (run.sh <elf> <out> play1 and gate.sh do this.)  Every "wait" ends one host frame
// (0.1 s), so the timeline is in host frames.
//
// e3m1 (Termination Central), skill 1.  Nothing fights near the start, so the player
// flies (noclip) to the deathmatch spot ({FIGHT_SPOT[0]:.0f} {FIGHT_SPOT[1]:.0f} {FIGHT_SPOT[2]:.0f}) next to grunts,
// enforcers and dogs, turns noclip off and fights with god mode, all weapons and quad
// damage (measurement window).  Then: scoreboard, view sizes, menus, console, a
// screenshot, and a noclip flight into the exit trigger, which starts the intermission.
// Noclip: velocity = wish velocity (no z from forward), clamped to 320; a key counts 0.5
// the frame it goes down, 1.0 while held, 0 the frame it is released; "+left;wait;-left"
// turns cl_yawspeed/20 degrees.
map {MAP}
alias w5 "wait;wait;wait;wait;wait"
alias w10 "w5;w5"
alias w50 "w10;w10;w10;w10;w10"
alias tl "+left;wait;-left"
alias tr "+right;wait;-right"
w10;w10
god
impulse 9
w5
impulse 7
noclip
wait
// down {abs(dz):.0f} units: {kz} frames
+movedown
{W(kz - 1)}
-movedown
// turn {b:+.1f} degrees
cl_yawspeed {abs(b) * 20:.1f}
{"tl" if b > 0 else "tr"}
// forward {dist:.0f} units: {kf} frames
+forward
{W(kf - 1)}
-forward
wait
noclip
w5
echo QSIM_WINDOW
""".splitlines()


